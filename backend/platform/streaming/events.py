from dataclasses import dataclass, asdict
import json
from typing import Any, Dict

@dataclass
class PlatformEvent:
    event_type: str
    data: Dict[str, Any]

    def to_json(self) -> str:
        return json.dumps({
            "event": self.event_type,
            "data": self.data
        })

